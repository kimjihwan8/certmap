# [이름] 가게 이름 정리
#   같은 가게도 '곽만근갈비탕(평내점)', '곽만근갈비탕 평내점', '(주)곽만근갈비탕'처럼 다르게 적힌다.
#   비교하기 전에 군더더기를 걷어낸 버전을 만든다. 원래 이름(name_raw)은 따로 남겨둔다.
# ════════════════════════════════════════════════════════════════════

# 법인 표기: 가게 이름의 일부가 아니라 회사 형태를 나타내는 말
_CORP = re.compile(r"\(주\)|\(유\)|\(사\)|㈜|주식회사|유한회사|농업회사법인|영농조합법인")

# '…점'으로 끝나지만 지점명이 아닌 단어들 (중화'반점', 편의'점', 술'주점' 등)
_NOT_BRANCH = {"반점", "상점", "매점", "주점", "본점", "점"}


def name_norm(name):
    """비교용 이름: 법인 표기를 지우고 한글·영문·숫자만 남긴 뒤 소문자로.

    역할: 띄어쓰기·괄호·특수문자 차이 때문에 같은 이름이 다르게 보이는 걸 막는다.
    예:
        '(주)이학'                              → '이학'
        '청풍 황금떡갈비'                        → '청풍황금떡갈비'
        '(주)볼드4 Bruxie(브럭시) 롯데월드몰점'    → '볼드4bruxie브럭시롯데월드몰점'
    """
    s = unicodedata.normalize("NFKC", name or "")
    s = _CORP.sub("", s)                               # 법인 표기 삭제
    return re.sub(r"[^0-9A-Za-z가-힣]", "", s).lower()  # 한글·영문·숫자가 아닌 글자 전부 삭제


def split_branch(name):
    """이름에서 지점명을 떼어 (본이름, 지점)으로 나눈다. 지점이 없으면 지점은 ''.

    역할: 상가는 '상호명'과 '지점명'을 따로 적지만 인증은 한 칸에 붙여 적는다.
          비교하려면 인증 쪽도 둘로 나눠야 한다.
    지점으로 보는 세 가지 모양:
        ① 끝의 괄호 안이 '…점'       '곽만근갈비탕(평내점)'  → ('곽만근갈비탕', '평내점')
        ② 띄어 쓴 마지막 단어가 '…점'  '반하정 수지본점'      → ('반하정', '수지본점')
        ③ 붙여 쓴 'N호점'            '따순밥2호점'          → ('따순밥', '2호점')
    지점이 아닌 경우:
        '중화반점', '홍콩 반점'  → '반점'은 중국집이라는 뜻이지 지점이 아니다
        '화심순두부본점'          → 띄어쓰기 없이 붙은 '본점'은 이름의 일부일 수 있어 건드리지 않는다
    """
    s = unicodedata.normalize("NFKC", name or "").strip()
    # ① 맨 끝 괄호 안이 '…점'
    m = re.search(r"\(([^()]*점)\)\s*$", s)
    if m and m.group(1) not in _NOT_BRANCH:
        return s[:m.start()].strip(), m.group(1)
    # ② 공백 뒤 마지막 단어가 '…점' (단 '반점'으로 끝나는 건 제외)
    m = re.search(r"\s(\S+점)$", s)
    if m and m.group(1) not in _NOT_BRANCH and not m.group(1).endswith("반점"):
        return s[:m.start()].strip(), m.group(1)
    # ③ 맨 끝이 숫자 + '호점'
    m = re.search(r"(\d+호점)$", s)
    if m and m.start() > 0:
        return s[:m.start()].strip(), m.group(1)
    return s, ""


def name_core(name):
    """지점명과 괄호 속 참고어까지 뗀 '본이름'의 비교용 버전.

    역할: 지점이 달라도 같은 브랜드인지, 지점 표기만 다른 같은 가게인지 볼 때 쓴다.
    예:
        '제주돈사돈(인덕원점)'  → '제주돈사돈'
        '냉면권가(冷麵權家)'    → '냉면권가'     ← 괄호 속 한자 병기 제거
    """
    base, _ = split_branch(name)          # 지점명 떼기 (_ 는 "지점은 안 쓴다"는 뜻)
    base = re.sub(r"\(.*?\)", "", base)    # 남은 괄호와 내용 지우기
    return name_norm(base)


