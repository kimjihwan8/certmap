# 정답 표기 자기 자신도 사전에 넣는다 ('서울특별시' → '서울특별시')
SIDO_ALIAS.update({s: s for s in SIDO_CANON})

# 주소 앞부분과 비교할 때 **긴 이름부터** 시도한다.
# 짧은 것부터 하면 '전남광주통합특별시 …'가 '전남'에서 먼저 걸려 뒤가 잘못 잘린다.
_SIDO_KEYS = sorted(SIDO_ALIAS, key=len, reverse=True)


def split_sido(addr):
    """주소 맨 앞의 시도를 찾아 정답 표기로 바꾸고, 나머지 주소와 함께 돌려준다.

    역할: 주소 안에만 시도가 들어 있는 소스(모범·백년·관광·식품안심)에서 시도를 뽑는다.
    입력: 주소 문자열
    출력: (정답 시도, 시도를 뗀 나머지 주소). 시도를 못 찾으면 ("", 원문)

    예:
        '서울 중구 세종대로 110'           → ('서울특별시', '중구 세종대로 110')
        '강원특별자치도원주시 단계동 1'     → ('강원특별자치도', '원주시 단계동 1')  ← 띄어쓰기 없이 붙은 표기
        '세종대로 110'                    → ('', '세종대로 110')                ← 시도가 아니라 도로명
    """
    s = addr.strip()
    for k in _SIDO_KEYS:                      # 긴 이름부터 하나씩 시도
        if s.startswith(k):                   # 주소가 이 시도 이름으로 시작하면
            rest = s[len(k):]                 # 시도 뒤에 남은 부분
            # 함정: '세종대로', '서울로'처럼 시도 이름으로 시작하는 **도로명**이 있다.
            # 시도 바로 뒤가 공백이 아니고 '로'·'대로'·'길'이 붙어 있으면 도로명으로 보고 건너뛴다.
            if rest[:1] and rest[:1] not in " \t" and re.match(r"(대?로|길)", rest):
                continue
            return SIDO_ALIAS[k], rest.strip()
    return "", s


def norm_sido(s):
    """시도 이름 하나만 정답 표기로 바꾼다. 모르는 이름이면 ''.

    역할: 시도가 별도 열로 있는 소스(착한가격 '시도', 안심식당 '시도명')에 쓴다.
    예: '서울' → '서울특별시', '전라북도' → '전북특별자치도', '엉뚱한값' → ''
    """
    return SIDO_ALIAS.get((s or "").strip(), "")


def sgg_city(sgg):
    """시군구에서 첫 단어만 남긴다.

    역할: 소스마다 시군구를 적는 세밀도가 달라서 비교 단위를 통일한다.
          상가는 '고양시 덕양구'까지 적고, 다른 소스는 '고양시'만 적기도 한다.
    예: '고양시 덕양구' → '고양시', '강남구' → '강남구', '' → ''
    """
    return (sgg or "").split()[0] if sgg else ""


