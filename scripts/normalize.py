def _selftest():
    """위 사례들을 전부 돌려서 기대한 결과와 다르면 어떤 게 틀렸는지 출력하고 실패로 끝낸다."""
    fails = 0
    for fn, cases in ((parse_road, _CASES_ROAD), (parse_jibun, _CASES_JIBUN),
                      (split_sido, _CASES_SIDO), (split_branch, _CASES_BRANCH)):
        for arg, want in cases:
            got = fn(arg)
            if got != want:
                fails += 1
                print(f"FAIL {fn.__name__}({arg!r}) = {got!r}, 기대 {want!r}")
    # 사례 표에 넣기 애매한 함수들은 assert(이 조건이 참이 아니면 즉시 멈춤)로 확인
    assert name_norm("(주)이학") == "이학"
    assert name_core("제주돈사돈(인덕원점)") == "제주돈사돈"
    assert name_core("냉면권가(冷麵權家)") == "냉면권가"
    assert license_year("20120364790") == "2012" and license_year("3000000-101") == ""
    assert norm_tel("042-282-3638") == "0422823638" and norm_tel("1234") == ""
    total = sum(len(c) for c in (_CASES_ROAD, _CASES_JIBUN, _CASES_SIDO, _CASES_BRANCH))
    if fails:
        raise SystemExit(f"{fails}/{total} 실패")
    print(f"정규화 자체 테스트 {total}건 + 단언 통과")


