# [주소] 주소 문자열 → 건물 키
#   "같은 건물인가?"를 비교하려면 주소에서 도로명과 건물번호만 정확히 뽑아야 한다.
#   '(상계동)', '1층', '101호' 같은 나머지는 소스마다 들쭉날쭉이라 버린다.
# ════════════════════════════════════════════════════════════════════

# 정규식 설명
#   [가-힣A-Za-z0-9.·]+  : 한글·영문·숫자·점이 1글자 이상
#   (대로|로|길)$        : '대로', '로', '길' 중 하나로 끝남
#   → '동일로', '시흥대로', '고척로40길', '3.1만세로' 같은 도로명 한 단어
_ROAD_TOKEN = re.compile(r"^[가-힣A-Za-z0-9.·]+(대로|로|길)$")

#   \d+(번)?[가-힣]?길$  : 숫자 + ('번') + (한글 한 글자) + '길'
#   → 도로명의 뒷부분만 따로 떨어져 나온 '185길', '14번길', '221번다길'
_ROAD_SUFFIX = re.compile(r"^\d+(번)?[가-힣]?길$")

#   (?:지하)?(\d+)(?:-(\d+))?  : ('지하') + 본번 + ('-' 부번)
#   → '1353', '43-1', '지하911' 에서 본번·부번을 꺼낸다
_NUM = re.compile(r"^(?:지하)?(\d+)(?:-(\d+))?")


def _tokens(addr):
    """주소를 깨끗하게 다듬은 뒤 띄어쓰기 단위 조각(토큰) 목록으로 자른다.

    역할: parse_road·parse_jibun 이 쓰는 준비 단계. 이름 앞의 '_'는 "이 파일 안에서만 쓴다"는 뜻.
    예: '서울 구로구 고척로40길 33- 3 1층' → ['서울', '구로구', '고척로40길', '33-3', '1층']

    처리하는 지저분한 표기들:
        '(상계동)'               괄호 속 참고항목         → 지운다
        '33- 3'                 하이픈 주변 공백          → '33-3'
        '중앙로121번길20방산빌딩'  도로명과 번호가 붙음       → '중앙로121번길 20방산빌딩'
        '지하 911'               '지하'와 번호가 떨어짐      → '지하911'
        '54, 지하1'             쉼표                    → 공백
    """
    s = unicodedata.normalize("NFKC", addr)            # 전각·특수 유니코드 표기 통일
    s = re.sub(r"\(.*?\)", " ", s)                     # 괄호와 그 안의 내용 제거
    s = re.sub(r"\s*-\s*", "-", s)                     # 하이픈 앞뒤 공백 제거
    s = re.sub(r"(대로|로|길)(지하)?(\d)", r"\1 \2\3", s)  # 도로명 끝과 숫자 사이에 공백 넣기
    s = re.sub(r"(지하)\s+(\d)", r"\1\2", s)           # '지하 911' → '지하911'
    return s.replace(",", " ").split()                 # 쉼표를 공백으로 바꾸고 공백 기준으로 자르기


def parse_road(addr):
    """도로명주소에서 (도로명, 건물번호)를 뽑는다. 못 찾으면 None.

    역할: 건물 키의 핵심 재료. 건물번호는 항상 '본번-부번' 모양으로 통일한다(부번 없으면 0).
    예:
        '서울특별시 노원구 동일로 1353 (상계동) 지하 1층' → ('동일로', '1353-0')
        '부산광역시 강서구 대저로221번다길 43-1'          → ('대저로221번다길', '43-1')
        '서울 영등포구 시흥대로 185길 11'                → ('시흥대로185길', '11-0')  ← 갈라진 도로명 붙이기
        '충청북도 청주시 청원구 내덕동 150-1'             → None                     ← 지번주소라 도로명 없음

    방법: 토큰을 앞에서부터 보면서 "도로명처럼 생긴 토큰 + 바로 뒤에 번호"인 자리를 찾는다.
          도로명이 띄어쓰기로 갈라진 세 가지 경우를 따로 처리한다(아래 ①②③).
    """
    t = _tokens(addr)
    for i, tok in enumerate(t):        # i = 몇 번째 토큰인지, tok = 그 토큰
        road = None                    # 이번 자리에서 찾은 도로명 (못 찾으면 None)
        if (_ROAD_SUFFIX.match(tok) and i > 0 and re.fullmatch(r"[가-힣]+", t[i - 1])
                and not re.search(r"(시|군|구|읍|면)$", t[i - 1])):
            # ① '동수 2길 35': 지금 토큰이 '2길'이고 앞 토큰이 한글 단어('동수')면 둘을 붙인다.
            #    단 앞 토큰이 '충주시'·'영동읍'처럼 행정구역이면 붙이지 않는다.
            road, j = t[i - 1] + tok, i + 1
        elif _ROAD_TOKEN.match(tok):
            # ② 일반적인 경우: '동일로' 같은 도로명 한 토큰
            road = tok
            j = i + 1                  # j = 건물번호가 있어야 할 자리 (도로명 바로 다음)
            # 바로 뒤가 '185길'이면 '시흥대로' + '185길' 로 붙인다
            if j < len(t) and _ROAD_SUFFIX.match(t[j]):
                road, j = road + t[j], j + 1
        elif i + 1 < len(t) and _ROAD_SUFFIX.match(t[i + 1]) and re.search(r"(동|리|가)$", tok):
            # ③ '인사동 14길5': 동 이름 + '14길' 이 갈라진 경우
            road, j = tok + t[i + 1], i + 2
        if road is None or j >= len(t):
            continue                   # 도로명이 아니거나 뒤에 토큰이 없으면 다음 자리로
        m = _NUM.match(t[j])           # 도로명 바로 다음 토큰이 번호인지 확인
        if m:
            # m.group(1) = 본번, m.group(2) = 부번(없으면 None → 0)
            # int() 로 감싸서 '007' 같은 앞자리 0도 없앤다
            return road, f"{int(m.group(1))}-{int(m.group(2) or 0)}"
    return None


# 지번주소의 동네 이름: 한글·숫자 + '동'/'리'/'가'로 끝남. 예: '소격동', '삼계리', '중화산동2가'
_JIBUN_DONG = re.compile(r"^[가-힣0-9]+(동|리|가)$")


def parse_jibun(addr):
    """지번주소에서 (법정동·리, 번지)를 뽑는다. 못 찾으면 None.

    역할: 도로명주소가 없는 경우의 대체 건물 키 재료. 모범음식점은 도로명주소가 24% 비어 있고
          대신 지번주소('소재지주소')가 100% 있다.
    예:
        '경상남도 창원시 마산회원구 내서읍 삼계리 26-8' → ('삼계리', '26-8')
        '서울특별시 종로구 소격동 48'                   → ('소격동', '48-0')
        '경상북도 경주시 양남면 효동리 산 7'             → ('효동리', '산7-0')  ← 산번지는 '산'을 붙여 구분
    """
    t = _tokens(addr)
    for i in range(len(t) - 1):
        if not _JIBUN_DONG.match(t[i]):    # 동·리 이름이 아니면 다음 토큰으로
            continue
        j, san = i + 1, ""                 # j = 번지가 있어야 할 자리
        if t[j] == "산" and j + 1 < len(t):            # '삼계리 산 12'
            j, san = j + 1, "산"
        elif t[j].startswith("산") and t[j][1:2].isdigit():   # '삼계리 산12'
            t[j], san = t[j][1:], "산"
        # 번지 모양: 본번 + ('-' 부번) + ('번지')
        m = re.match(r"^(\d+)(?:-(\d+))?(?:번지)?$", t[j])
        if m:
            return t[i], f"{san}{int(m.group(1))}-{int(m.group(2) or 0)}"
    return None


def road_key(sido, addr):
    """건물 키(도로명 기준)를 만든다: '시도|도로명|본번-부번'. 못 만들면 ''.

    역할: 인증과 상가가 "같은 건물"인지 비교하는 열쇠. 이 문자열이 같으면 같은 건물이다.
    예: ('서울특별시', '노원구 동일로 1353 (상계동)') → '서울특별시|동일로|1353-0'

    시군구를 키에 넣지 않은 이유: 인천 구 개편(2026, '중구'→'제물포구' 등)처럼 소스마다
    시군구 이름이 다를 수 있다. 시군구는 매칭할 때 따로 비교한다.
    """
    r = parse_road(addr)
    return f"{sido}|{r[0]}|{r[1]}" if sido and r else ""


def jibun_key(sido, addr):
    """건물 키(지번 기준)를 만든다: '시도|법정동|번지'. 못 만들면 ''.

    역할: road_key 를 못 만들 때 쓰는 대체 열쇠.
    예: ('경상남도', '창원시 마산회원구 내서읍 삼계리 26-8') → '경상남도|삼계리|26-8'
    """
    r = parse_jibun(addr)
    return f"{sido}|{r[0]}|{r[1]}" if sido and r else ""


