def norm_tel(tel):
    """전화번호에서 숫자만 남긴다. 9자리 미만이면 잘못된 값으로 보고 ''.

    역할: 인증끼리(모범음식점 ↔ 안심식당) 비교하는 보조 열쇠. 상가에는 전화번호가 없다.
    예: '042-282-3638' → '0422823638', '1234' → ''
    """
    d = re.sub(r"\D", "", tel or "")      # \D = 숫자가 아닌 글자 → 전부 삭제
    return d if len(d) >= 9 else ""


def license_year(no):
    """인허가번호 앞 4자리에서 인허가 연도를 꺼낸다. 형식이 다르면 ''.

    역할: 상가 데이터에는 개업일이 없다. 인허가 연도로 "얼마나 오래된 가게인가"를 대신 가늠한다.
          (모범음식점·식품안심업소의 인허가번호는 연도 4자리 + 7자리 숫자 형식)
    예: '19990025158' → '1999', '3000000-101' → ''
    """
    m = re.match(r"^((?:19|20)\d{2})\d{7}$", (no or "").strip())
    return m.group(1) if m else ""


def stable_id(*parts):
    """원본에 고유번호가 없는 소스용 ID를 만든다.

    역할: 착한가격업소·백년가게에는 행마다 고유번호가 없다. 나중에 "이 결과가 원본의 어느 줄이었나"를
          추적하려면 ID가 필요하다. 행 번호를 쓰면 데이터가 갱신돼 순서가 바뀔 때 ID도 바뀌므로,
          이름+주소로 해시(지문)를 만든다. 같은 이름·주소면 언제 만들어도 같은 ID가 나온다.
    예: stable_id('늘채움', '전북 전주시 …') → '3f9a1c0b2e7d' 같은 12자리 문자열
    """
    return hashlib.sha1("|".join(parts).encode()).hexdigest()[:12]


